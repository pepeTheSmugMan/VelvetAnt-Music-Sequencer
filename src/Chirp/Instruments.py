import numpy as np
from scipy import signal
from abc import ABC, abstractmethod
from matplotlib import pyplot as plt

class Instrument(ABC):
    """abstract class for implementing synth instruments"""

    sample_rate = 48000
    volume = 0.5

    @abstractmethod
    def create_tone(self) -> np.ndarray:
        pass

    @staticmethod
    def _create_t(sample_rate: int, duration: float) -> np.ndarray:
        """returns time function"""
        return np.arange(sample_rate * duration) / sample_rate

    @staticmethod
    def _normalise(tone: float, volume: float) -> np.ndarray:
        """normalises audio and sets to given volume"""
        return volume * np.clip(tone, -1, 1)

    @staticmethod
    def _terminal_fade(tone) -> np.array:
        """removes clicking from end of audio sample"""
        fade = np.linspace(1.0, 0.0, 100)
        tone[-100:] *= fade
        return tone

    def create_melody(self, segment, speed=1.0) -> np.array:
        """turns a segment into np.array melody"""
        output = np.zeros(int(self.sample_rate * segment.duration * speed))
        for note in segment.notes:

            sound = self.create_tone(note.duration * speed, note.pitch)
            index = int(self.sample_rate * note.start * speed)

            output[index:(index+len(sound))] += sound
        
        return np.clip(output, -1, 1)



class SimpleTone(Instrument):
    """Provides interface for synthesizing sound from a mathematical function, e.g. numpy.sin"""

    def __init__(self, _tone_function:callable):
        self._tone_function = _tone_function
    
    def _create_phase(self, t: np.ndarray, frequency: float) -> np.ndarray:
        return 2 * np.pi * frequency * t

    def create_tone(self, duration: float, frequency: float, volume: float = None) -> np.ndarray:
        """
        Returns a numpy array containing waveform generated by mathematical function contained in self._tone_function,
        lasting specified duration (in seconds)
        """
        if volume == None:
            volume = self.volume

        t = self._create_t(Instrument.sample_rate, duration)
        phase = self._create_phase(t, frequency)
        tone = self._tone_function(phase)
        tone = self._normalise(tone, volume)
        return self._terminal_fade(tone)
    

class DialTone(Instrument):
    """Provides interface for synthesizing sound from a mathematical function, e.g. numpy.sin,
    switching between frequency based on given on - drop, in interval"""

    def __init__(self, _tone_function:callable, interval: int, frequencyDrop: int):
        self._tone_function = _tone_function
        self.interval = interval
        self.frequencyDrop = frequencyDrop

    def _create_phase(self, t: np.ndarray, frequency: float) -> np.ndarray:

        interval = Instrument.sample_rate/self.interval
        speed = np.where(
            (np.arange(len(t)) // interval ) % 2 == 0,
            frequency, 
            frequency-self.frequencyDrop
        )
        return 2 * np.pi * np.cumsum(np.diff(t, prepend=0) * speed)
    
    def create_tone(self, duration, frequency, volume=1.0):
        if volume == None:
            volume = self.volume
        t = self._create_t(Instrument.sample_rate, duration)
        phase = self._create_phase(t, frequency)
        tone = self._tone_function(phase)
        tone = self._normalise(tone, volume)
        return self._terminal_fade(tone)


class Sawtooth(SimpleTone):
    """
    Inherits from SimpleTone, implements signal.sawtooth as tone generator. 
    0.5 for Triangle wave, other values for Sawtooth.
    """

    def __init__(self, width: float=0.5):
        if width < 0.0 or width > 1.0:
            raise ValueError("Sawtooth width has to be a value between 0.0 and 1.0!")
        self.width = width
    
    def _tone_function(self, phase: np.ndarray) -> np.ndarray:
        return signal.sawtooth(phase, self.width)


class Noise(Instrument):
    """
    Generates a waveform from random noise.
    Instead of frequency, it uses repeat to repeat each random value in the array, e.g.
    at random = 2, array [x1 x2 x3] would turn into [x1 x1 x2 x2 x3 x3]
    (and then get cut in half, to keep duration the same)
    """

    def _create_phase(self, duration: float) -> np.ndarray:
        return np.random.rand(int(Instrument.sample_rate*duration))
    

    def create_tone(self, duration: float, frequencyHigh: float, frequencyLow: float, volume: float = None, interval: int=20) -> np.ndarray:
        """
        Returns a numpy array containing waveform generated by mathematical function contained in self._tone_function,
        alternating between high and low frequencies according to interval (the higher, the faster),
        lasting specified duration (in seconds).
        """
        if volume == None:
            volume = self.volume
        t = self._create_t(Instrument.sample_rate, duration)
        phase = self.create_dialtone_phase(t, frequencyHigh, frequencyLow, interval)
        return self._create_tone_from_phase(phase, volume)


class Silence(Instrument):
    """Test instrument used for creating blank samples"""

